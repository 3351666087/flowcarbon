/** Fills `{name}` placeholders in a line of copy. */
/** Fills in `{name}`, and `{name|one|other}` by whether that value is 1: an English noun that has to agree with it. */
export function fill(template: string | undefined, vars: Record<string, string | number>) {
  return (template ?? "")
    .replace(/\{(\w+)\|([^|}]*)\|([^}]*)\}/g, (_m, k: string, one: string, other: string) =>
      Number(vars[k]) === 1 ? one : other,
    )
    .replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

